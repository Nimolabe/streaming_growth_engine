class Format:
    id: str
    genre: str | None  # None = allgemeines Format für Spiele ohne erkanntes Genre
    needs_chat: ChatNeed
    goals: tuple[Goal, ...]
    name: Text
    steps: tuple[Text, Text, Text]
    prep: tuple[Text, Text]
    hook: Text
    clip: Text
    metric: Text
    title: Text
    tags: tuple[Text, ...]
    needs_collab: bool = False
    expert: bool = False  # setzt Erfahrung voraus (für Einsteiger weiter hinten)
    series: tuple[Text, ...] = field(default=())



