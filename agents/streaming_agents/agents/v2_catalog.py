"""Curated content mechanics; each is an editorial hypothesis, not proven growth.

Method references support *principles*, never guarantee that a specific format will work.
The library has no external requests, tracking or generated claims.
"""

from dataclasses import dataclass

SOURCES = {
    "twitch_camp": "https://www.twitch.tv/creatorcamp/en/",
    "twitch_analytics": "https://help.twitch.tv/s/article/channel-analytics",
    "youtube_shorts": "https://support.google.com/youtube/answer/11914225?hl=en",
    "tiktok_structure": "https://ads-useast2a.tiktok.com/resources/help/article/creative-best-practices?lang=en",
}


@dataclass(frozen=True)
class Format:
    id: str
    title_de: str
    title_en: str
    mechanism: str
    genre: str
    style: str
    goal: str
    min_hours: int
    steps_de: tuple[str, str, str]
    steps_en: tuple[str, str, str]
    hook_de: str
    hook_en: str
    clip_de: str
    clip_en: str
    metric_de: str
    metric_en: str
    source_ids: tuple[str, ...]


def make(
    id: str,
    title_de: str,
    title_en: str,
    mechanism: str,
    genre: str,
    style: str,
    goal: str,
    min_hours: int,
    steps_de: tuple[str, str, str],
    steps_en: tuple[str, str, str],
    hook_de: str,
    hook_en: str,
    clip_de: str,
    clip_en: str,
    metric_de: str,
    metric_en: str,
    sources: tuple[str, ...] = ("twitch_camp", "youtube_shorts"),
) -> Format:
    return Format(
        id, title_de, title_en, mechanism, genre, style, goal, min_hours,
        steps_de, steps_en, hook_de, hook_en, clip_de, clip_en,
        metric_de, metric_en, sources,
    )


